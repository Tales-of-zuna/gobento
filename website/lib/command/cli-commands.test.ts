/**
 * Cross-check with the CLI (spec: Generated commands are accepted by the CLI).
 *
 * For every selection the CLI supports (`supported` in catalog.json, with and
 * without a frontend), this builds the configurator's command twice: with the defaults, and with every
 * flag explicit (module path, the Go range floor, each library pinned to its
 * range floor). The commands are kept in `supported-commands.txt`, which the
 * Go test `TestWebsiteCommands` in internal/cli runs with `--dry-run`. The
 * command builder is thus exercised as it is, with no copy of it in Go; a
 * stale file fails this test (regenerate it with `pnpm test -u`).
 */
import { describe, expect, it } from 'vitest';
import { selectedModules } from '@/lib/catalog/compat';
import { catalog } from '@/lib/catalog/data';
import { KIND_IDS, type Catalog } from '@/lib/catalog/schema';
import { compareVersions, parseVersion, type VersionKind } from '@/lib/catalog/semver';
import { buildCommand, type ConfigState } from './build';

/** Returns the lowest version a range allows: its highest `>=` or `=` operand. */
function floor(range: string, kind: VersionKind): string {
  const operands = range
    .trim()
    .split(/\s+/)
    .flatMap((term) => /^(?:>=|=)(.+)$/.exec(term)?.[1] ?? []);
  const sorted = operands.sort((a, b) =>
    compareVersions(parseVersion(a, kind)!, parseVersion(b, kind)!),
  );
  const bound = sorted.at(-1);
  if (bound === undefined) throw new Error(`range ${range} has no lower bound`);
  return bound;
}

/** The configurator states whose commands are cross-checked. */
function states(cat: Catalog): { label: string; state: ConfigState }[] {
  return cat.supported.flatMap((components) => {
    // The CLI's own spelling of a selection: one name per chosen kind, in
    // flag order, so a selection without a frontend has four parts.
    const label = KIND_IDS.flatMap((kind) => components[kind] ?? []).join('/');
    const pins = Object.fromEntries(
      selectedModules(cat, { components, go: cat.go.default, pins: {} })
        .filter((m) => m.role === 'library')
        .map((m) => [m.path, floor(m.range, 'module')]),
    );
    return [
      {
        label: `${label}, defaults`,
        state: { name: 'shop', module: '', components, go: cat.go.default, pins: {} },
      },
      {
        label: `${label}, explicit module and range floors`,
        state: {
          name: 'shop',
          module: 'example.com/shop',
          components,
          go: floor(cat.go.range, 'go'),
          pins,
        },
      },
    ];
  });
}

describe('commands for every supported selection', () => {
  const cases = states(catalog);

  it.each(cases)('builds a command for $label', ({ state }) => {
    expect(buildCommand(catalog, state).ok).toBe(true);
  });

  it('matches supported-commands.txt, which the CLI cross-check runs', async () => {
    const lines = cases.map(({ label, state }) => {
      const result = buildCommand(catalog, state);
      return `# ${label}\n${result.ok ? result.command : 'no command'}`;
    });
    const header =
      '# Generated by website/lib/command/cli-commands.test.ts (pnpm test -u);\n' +
      '# run with --dry-run by TestWebsiteCommands in internal/cli. Do not edit.\n';
    await expect(`${header}${lines.join('\n')}\n`).toMatchFileSnapshot('./supported-commands.txt');
  });
});
